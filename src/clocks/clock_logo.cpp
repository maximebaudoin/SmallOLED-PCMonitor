// ========== Logo Display ==========
void displayClockWithLogo() {
  // Center the logo on the screen.
  int logo_x = (SCREEN_WIDTH - LOGO_WIDTH) / 2;
  int logo_y = (SCREEN_HEIGHT - LOGO_HEIGHT) / 2;
  if (logo_x < 0) logo_x = 0;
  if (logo_y < 0) logo_y = 0;

  display.drawBitmap(logo_x, logo_y, LOGO_BITMAP, LOGO_WIDTH, LOGO_HEIGHT,
                     DISPLAY_WHITE);

  // Draw no-WiFi icon if disconnected
  if (!wifiConnected) {
    drawNoWiFiIcon(0, 0);
  }
}
